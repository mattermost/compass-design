#!/usr/bin/env node
/**
 * Writes TypeScript wrappers + name catalog for Compass illustration SVGs,
 * plus lazy loaders for the guidelines specimen grid.
 *
 * Source of truth: packages/compass-ui/src/illustrations/*.svg
 */
import { writeFileSync, readdirSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(__dirname, '..');
const illustrationsDir = join(
  repoRoot,
  'packages/compass-ui/src/illustrations',
);

function listIllustrationNames() {
  return readdirSync(illustrationsDir)
    .filter((file) => file.endsWith('.svg'))
    .map((file) => file.replace(/\.svg$/, ''))
    .sort((a, b) => a.localeCompare(b));
}

const names = listIllustrationNames();
if (names.length === 0) {
  throw new Error(`No SVG illustrations found in ${illustrationsDir}`);
}

const header =
  '/* Generated by scripts/gen-compass-illustrations.mjs — do not edit by hand */\n';

for (const name of names) {
  writeFileSync(
    join(illustrationsDir, `${name}.ts`),
    `${header}export { default } from './${name}.svg?react';\n`,
    'utf8',
  );
}

const namesLiteral = names.map((n) => `  '${n}',`).join('\n');
writeFileSync(
  join(illustrationsDir, 'names.ts'),
  `${header}
export const ILLUSTRATION_NAMES = [
${namesLiteral}
] as const;

export type IllustrationName = (typeof ILLUSTRATION_NAMES)[number];
`,
  'utf8',
);

const loadersDir = join(
  repoRoot,
  'src/guidelines/foundations/illustrations',
);
mkdirSync(loadersDir, { recursive: true });

const loadersBody = names
  .map(
    (n) =>
      `  '${n}': () => import('@mattermost/compass-ui/illustrations/${n}'),`,
  )
  .join('\n');

writeFileSync(
  join(loadersDir, 'illustrationImports.generated.ts'),
  `${header}import type { ComponentType, SVGProps } from 'react';

export type CompassIllustration = ComponentType<SVGProps<SVGSVGElement>>;

export const ILLUSTRATION_LOADERS: Record<
  string,
  () => Promise<{ default: CompassIllustration }>
> = {
${loadersBody}
};
`,
  'utf8',
);

console.log(
  `Wrote ${names.length} illustration wrappers, names.ts, and docs loaders`,
);
